"""Band status icons for src/render.c, drawn at 8x and reduced to the
panel's four greys (the font thresholds of mkfont.py) so the curves come out
smooth. Prints ASCII previews and the C tables.

    uv run firmware/tools/mkicons.py

Columns are 24 rows tall: bit 23 = top row. Each icon has two tables: the
hi word (1 = dark grey or black: the 1 bpp icon at threshold 110) and the lo
word (1 = light grey or black). A pixel with neither bit is white.
"""
import math

from PIL import Image, ImageDraw

S = 8  # supersampling


LIGHT_THR, DARK_THR, BLACK_THR = 40, 110, 200   # as mkfont.py (thr 110)


def finish(img, w, h):
    """Ink level per pixel: 0 white, 1 light grey, 2 dark grey, 3 black."""
    small = img.resize((w, h), Image.LANCZOS)

    def lvl(v):
        return 3 if v >= BLACK_THR else 2 if v >= DARK_THR else 1 if v >= LIGHT_THR else 0
    return [[lvl(small.getpixel((x, y))) for x in range(w)] for y in range(h)]


# ---- Wi-Fi: dot and two rounded arcs, 24 x 20, at rows 2..21 of the cell
WW, WH = 25, 20
CX, CY = 12.5, 18.0          # fan centre (below the dot)
SPREAD = 46                  # degrees each side of vertical
ARCS = (7.6, 13.6)           # centre-line radii
THICK = 3.0


def arc_pts(r, n=48):
    a0, a1 = math.radians(-90 - SPREAD), math.radians(-90 + SPREAD)
    return [(CX + r * math.cos(a0 + (a1 - a0) * i / n), CY + r * math.sin(a0 + (a1 - a0) * i / n))
            for i in range(n + 1)]


def stroke(d, pts, width, caps=True):
    """Polyline with round joins, and round caps unless caps=False."""
    sc = [(x * S, y * S) for x, y in pts]
    d.line(sc, fill=255, width=round(width * S))
    for x, y in ((sc[0], sc[-1]) if caps else ()) + tuple(sc[1:-1]):
        rr = width * S / 2
        d.ellipse((x - rr, y - rr, x + rr, y + rr), fill=255)


def wifi(kind):
    img = Image.new("L", (WW * S, WH * S), 0)
    d = ImageDraw.Draw(img)
    r = 2.4
    d.ellipse(((CX - r) * S, (CY - 1.6 - r) * S, (CX + r) * S, (CY - 1.6 + r) * S), fill=255)
    for rad in ARCS:
        pts = arc_pts(rad)
        stroke(d, pts, THICK)
        if kind == "wait":  # hollow arcs: "not connected yet"
            hollow = [(x * S, y * S) for x, y in pts[2:-2]]
            d.line(hollow, fill=0, width=round(1.1 * S))
    if kind == "err":  # slash with a white halo
        p0, p1 = (WW - 2.5, 1.5), (3.0, WH - 1.0)
        d.line([(p0[0] * S, p0[1] * S), (p1[0] * S, p1[1] * S)], fill=0, width=round(5.4 * S))
        stroke(d, [p0, p1], 2.2)
    return finish(img, WW, WH)


# ---- Battery: rounded body 26 x 14 (2 px outline), detached nub, 30 x 14
BW, BH = 30, 14


def battery_outline():
    img = Image.new("L", (BW * S, BH * S), 0)
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((0, 0, 26 * S - 1, BH * S - 1), radius=3.2 * S, fill=255)
    d.rounded_rectangle((2 * S, 2 * S, 24 * S - 1, (BH - 2) * S - 1), radius=1.4 * S, fill=0)
    d.rounded_rectangle((27 * S, 4 * S, 30 * S - 1, (BH - 4) * S - 1), radius=1.2 * S, fill=255)
    return finish(img, BW, BH)


BOLT = ["......##",  # 8 x 8, XORed over the fill while charging
        ".....##.",
        "....##..",
        "..######",
        "######..",
        "..##....",
        ".##.....",
        "##......"]


def show(name, g):
    print(name)
    for row in g:
        print("".join(".-+#"[int(v)] for v in row))


def cols(g, top, plane=None):
    """24-row column words, the bitmap's row 0 at cell row `top`. plane "hi":
    dark grey or black, "lo": light grey or black, None: any ink (1 bpp)."""
    h, w = len(g), len(g[0])
    on = {"hi": (2, 3), "lo": (1, 3), None: (1, 2, 3)}[plane]
    return [sum(1 << (23 - (top + y)) for y in range(h) if g[y][x] in on) for x in range(w)]


def c_rows(ws):
    return "{" + ", ".join("0x%06X" % c for c in ws) + "}"


if __name__ == "__main__":
    W_TOP, B_TOP = -2, 1  # wifi rows 0..2 are empty, so -2 still keeps all ink
    for k in ("wait", "ok", "err"):
        show(k, wifi(k))
    show("battery", battery_outline())
    show("bolt", [[3 if c == "#" else 0 for c in r] for r in BOLT])
    print(f"/* generated by tools/mkicons.py; LINK_* order: wait, ok, err; rows {W_TOP}..;")
    print("   [..][0] hi word (dark grey or black), [..][1] lo word (light grey or black) */")
    print(f"static const uint32_t wifi_cols[3][2][WIFI_W] = {{")
    for k in ("wait", "ok", "err"):
        g = wifi(k)
        print(f"    {{{c_rows(cols(g, W_TOP, 'hi'))},\n     {c_rows(cols(g, W_TOP, 'lo'))}}},")
    print("};")
    b = battery_outline()
    print(f"static const uint32_t bat_outline[2][BAT_W] = {{{c_rows(cols(b, B_TOP, 'hi'))},\n"
          f"    {c_rows(cols(b, B_TOP, 'lo'))}}};")
    bolt = [[3 if c == "#" else 0 for c in r] for r in BOLT]
    print(f"static const uint32_t bolt_cols[8] = {c_rows(cols(bolt, B_TOP + 3))};")
