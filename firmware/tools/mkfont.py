"""Rasterise the OFL font (Barlow Condensed) into 2 bpp glyph tables for the
e-paper renderer.  Writes src/fonts_gen.c and src/fonts_gen.h (committed;
the Makefile does not regenerate them).

    uv run firmware/tools/mkfont.py [--out-dir firmware/src] [--dump-dir DIR]

Storage format (see fonts_gen.h):
  * A glyph is stored column by column.  A column is two planes of `hb` bytes
    (hi plane, then lo plane), each covering landscape y = 0 .. 8*hb-1 of the
    font cell, MSB first (y = 0 is bit 7 of byte 0), the same orientation as
    one panel row (= one landscape x).
  * A pixel is the 2-bit code hi:lo of the panel's grey mode (DTM1:DTM2):
    11 white, 10 light grey, 01 dark grey, 00 black.  Cell padding is 0xFF,
    and glyphs combine by taking the darker code (render.c).
  * The hi plane alone (0 = dark or black) is the 1 bpp font at threshold
    `thr`, used when the panel is refreshed in black and white.
  * Each glyph is trimmed of blank left/right columns:  `lsb` is the offset of
    its first stored column from the pen position, `w` the stored columns,
    `adv` the pen advance.
  * Characters map to glyphs through a per-font byte table over
    [first..last] (0xFF = absent).  '*' is the degree sign in every font.
"""
import argparse
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
FONTDIR = HERE.parent / "fonts"
BOLD = FONTDIR / "BarlowCondensed-Bold.ttf"
SEMI = FONTDIR / "BarlowCondensed-SemiBold.ttf"

DIGITS = "0123456789"
SMALL_SET = (" " + DIGITS + "%:-./*,'"
             "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz")

# name, ttf, reference char, reference height px, cell px (mult. of 8),
# baseline row inside the cell, charset, threshold (0..255: dark grey or black
# if coverage >=; light grey from LIGHT_THR, black from BLACK_THR), extra pen
# advance per glyph
FONTS = [
    # clock/band font: 40 px cell, digits 32 px high at y 4..35
    dict(name="clk",   ttf=BOLD, ref="1", refh=32, cell=40, base=36,
         chars=" " + DIGITS + "-.:%*CF", thr=110, track=1),
    # small text: cap height 11, baseline at y 13 of a 16 px cell
    dict(name="small", ttf=SEMI, ref="H", refh=11, cell=16, base=13,
         chars=SMALL_SET, thr=120, track=1),
    # status message title (fallback screen): cap height 16, baseline at y 20
    dict(name="msg",   ttf=SEMI, ref="H", refh=16, cell=24, base=20,
         chars=SMALL_SET, thr=120, track=1),
]


LIGHT_THR = 40
BLACK_THR = 200


def level(v, thr):
    """Coverage 0..255 -> 2-bit code (3 white, 2 light, 1 dark, 0 black)."""
    if v >= BLACK_THR:
        return 0
    if v >= thr:
        return 1
    if v >= LIGHT_THR:
        return 2
    return 3


def pick_size(path, ref, refh):
    for sz in range(8, 400):
        f = ImageFont.truetype(str(path), sz)
        t = f.getbbox(ref, anchor="ls")[1]
        if -t >= refh:
            return sz
    raise SystemExit("size search failed")


def glyph_char(c):
    return "°" if c == "*" else c


def raster(spec):
    sz = pick_size(spec["ttf"], spec["ref"], spec["refh"])
    font = ImageFont.truetype(str(spec["ttf"]), sz)
    cell, base, thr = spec["cell"], spec["base"], spec["thr"]
    pad = 16
    glyphs = []
    for c in spec["chars"]:
        ch = glyph_char(c)
        adv = int(round(font.getlength(ch))) + spec["track"]
        wimg = adv + 2 * pad + 8
        im = Image.new("L", (wimg, cell), 0)
        ImageDraw.Draw(im).text((pad, base), ch, font=font, fill=255, anchor="ls")
        px = im.load()
        cols = []
        for x in range(wimg):
            cols.append([level(px[x, y], thr) for y in range(cell)])
        ink = [x for x, col in enumerate(cols) if any(v != 3 for v in col)]
        if ink:
            x0, x1 = ink[0], ink[-1]
            cols = cols[x0:x1 + 1]
            lsb = x0 - pad
        else:
            cols, lsb = [], 0
        packed = bytearray()
        for col in cols:
            for bit in (2, 1):  # hi plane, then lo plane
                for k in range(cell // 8):
                    v = 0xFF
                    for b in range(8):
                        if not col[k * 8 + b] & bit:
                            v &= ~(0x80 >> b)
                    packed.append(v)
        glyphs.append(dict(c=c, w=len(cols), adv=adv, lsb=lsb, data=bytes(packed), cols=cols))
    return sz, glyphs


def emit(out_dir, dump_dir):
    c = ["/* Generated by firmware/tools/mkfont.py from Barlow Condensed (SIL OFL 1.1,",
         "   see firmware/fonts/OFL.txt).  Do not edit. */",
         '#include "fonts_gen.h"', ""]
    h = ["/* Generated by firmware/tools/mkfont.py.  Do not edit.",
         "   Glyph format: column-major in landscape y.  A column is 2*hb bytes:",
         "   the hi plane, then the lo plane, each landscape y = 0..8*hb-1 of the",
         "   cell, MSB first.  Pixel = hi:lo, 11 white, 10 light grey, 01 dark",
         "   grey, 00 black (the panel's DTM1:DTM2 grey code).",
         "   Glyph g covers columns [pen+lsb, pen+lsb+w); pen advances by adv.",
         "   Char map: byte table over [first..last], 0xFF = no glyph.",
         "   '*' is the degree sign. */",
         "#ifndef FONTS_GEN_H", "#define FONTS_GEN_H", "#include <stdint.h>", "",
         "typedef struct { uint16_t off; uint8_t w; uint8_t adv; int8_t lsb; } glyph_t;",
         "typedef struct {",
         "  const glyph_t *g;      /* glyph table                       */",
         "  const uint8_t *map;    /* char - first -> glyph index/0xFF  */",
         "  const uint8_t *bits;   /* column data                       */",
         "  uint8_t first, last;   /* char range of map                 */",
         "  uint8_t hb;            /* bytes per plane of a column (cell / 8) */",
         "} font_t;", ""]
    total = 0
    for spec in FONTS:
        n = spec["name"]
        sz, gl = raster(spec)
        chars = sorted(spec["chars"])
        first, last = ord(chars[0]), ord(chars[-1])
        order = sorted(gl, key=lambda g: g["c"])
        mp = [0xFF] * (last - first + 1)
        for i, g in enumerate(order):
            mp[ord(g["c"]) - first] = i
        blob = bytearray()
        offs = []
        for g in order:
            offs.append(len(blob))
            blob += g["data"]
        assert len(blob) < 65536
        c.append(f"static const uint8_t {n}_bits[{len(blob)}] = {{")
        for i in range(0, len(blob), 24):
            c.append("  " + ",".join(f"0x{b:02X}" for b in blob[i:i + 24]) + ",")
        c.append("};")
        c.append(f"static const uint8_t {n}_map[{len(mp)}] = {{")
        for i in range(0, len(mp), 24):
            c.append("  " + ",".join(f"{b}" for b in mp[i:i + 24]) + ",")
        c.append("};")
        c.append(f"static const glyph_t {n}_g[{len(order)}] = {{")
        for g, o in zip(order, offs):
            ch = g["c"] if g["c"] not in "\\'" else "\\" + g["c"]
            c.append(f"  {{{o},{g['w']},{g['adv']},{g['lsb']}}}, /* '{ch}' */")
        c.append("};")
        c.append(f"const font_t font_{n} = {{ {n}_g, {n}_map, {n}_bits, {first}, {last}, {spec['cell']//8} }};")
        c.append("")
        h.append(f"extern const font_t font_{n};  /* {spec['cell']} px cell, ref '{spec['ref']}' {spec['refh']} px (pt {sz}) */")
        size = len(blob) + len(mp) + 6 * len(order) + 12
        total += size
        print(f"{n:6s} pt{sz:3d} glyphs={len(order):3d} bits={len(blob):5d} map={len(mp):3d} "
              f"tbl={6*len(order):4d} -> {size} B", file=sys.stderr)
        if dump_dir:
            dump(dump_dir, n, order, spec)
    h += ["", "#endif", ""]
    (out_dir / "fonts_gen.c").write_text("\n".join(c) + "\n")
    (out_dir / "fonts_gen.h").write_text("\n".join(h))
    print(f"TOTAL font flash: {total} B (limit 16384)", file=sys.stderr)
    if total > 16384:
        raise SystemExit("font budget exceeded")


def dump(d, n, order, spec):
    d.mkdir(parents=True, exist_ok=True)
    W = sum(g["adv"] + 4 for g in order) + 8
    im = Image.new("L", (W, spec["cell"] + 4), 255)
    x = 4
    for g in order:
        for i, col in enumerate(g["cols"]):
            for y, v in enumerate(col):
                if v != 3:
                    im.putpixel((x + g["lsb"] + i, y + 2), v * 85)
        x += g["adv"] + 4
    im.save(d / f"font_{n}.png")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", type=Path, default=HERE.parent / "src")
    ap.add_argument("--dump-dir", type=Path)
    a = ap.parse_args()
    emit(a.out_dir, a.dump_dir)
